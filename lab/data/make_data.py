def rows(items):
    return [{"anchor": q, "positive": d} for d, qs in items for q in qs]


def check():
    ev_docs, tr_docs = [d for d, _ in EVAL], [d for d, _ in TRAIN]
    ev_q = [q for _, qs in EVAL for q in qs]
    tr_q = [q for _, qs in TRAIN for q in qs]
    assert len(EVAL) == 20 and len(TRAIN) == 94, (len(EVAL), len(TRAIN))
    assert all(len(qs) == 3 for _, qs in EVAL + TRAIN)
    assert len(set(ev_docs)) == 20 and len(set(tr_docs)) == 94, "세트 안 문서 중복"
    assert not set(ev_docs) & set(tr_docs), "평가·학습 문서 겹침"
    assert len(set(ev_q + tr_q)) == len(ev_q + tr_q), "질의 중복"


if __name__ == "__main__":
    check()
    here = os.path.dirname(os.path.abspath(__file__))
    for name, items in [("eval", EVAL), ("train", TRAIN)]:
        rs = rows(items)
        with open(os.path.join(here, f"{name}.jsonl"), "w", encoding="utf-8") as f:
            for r in rs:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        print(f"{name}.jsonl: {len(rs)}쌍, 문서 {len(items)}개")
